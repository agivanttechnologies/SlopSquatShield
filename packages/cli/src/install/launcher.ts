import { execFileSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import type { SelfLocation } from './self-location.js';

/**
 * The launcher is the one fixed, tool-owned path every surface (hooks, shell snippets, CI
 * shims) calls instead of a bare `slopsquatshield` — a bare name only works if the calling
 * host's PATH happens to contain the install dir, which nvm/fnm/volta/Homebrew/Windows/WSL
 * and every non-interactive hook shell break (seen 2026-10-01: a hook failing with exit 127 under nvm). The
 * launcher records the current Node + CLI entry as absolute paths, so it keeps working
 * across Node switches; `init` (or a self-heal, see `refreshLauncherIfStale`) refreshes it.
 */
export const LAUNCHER_NAME = 'slopsquatshield';
export const SHIM_DIR_ENV = 'SLOPSQUATSHIELD_SHIM_DIR';

/**
 * What a stale launcher prints. It must make sense after `npm uninstall -g`, not only after a
 * Node switch, so it doesn't just say "run init" (#3). One line, ASCII only: it goes into sh,
 * cmd and PowerShell scripts alike.
 */
export const STALE_MESSAGE = `slopsquatshield: launcher is stale - the program it points to is gone (uninstalled, or Node moved). Reinstall it and run 'slopsquatshield init', or remove SlopSquatShield's block from your shell profile and its agent-hook entries.`;

export function launcherDir(home: string = homedir()): string {
  return join(home, '.config', 'slopsquatshield', 'bin');
}

/** The single path surfaces invoke: `.cmd` on Windows, the extensionless `sh` script elsewhere. */
export function launcherPath(
  home: string = homedir(),
  platform: string = process.platform,
): string {
  return join(launcherDir(home), platform === 'win32' ? `${LAUNCHER_NAME}.cmd` : LAUNCHER_NAME);
}

function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/**
 * POSIX launcher (Linux, macOS, WSL, and Git Bash on Windows). Order of preference:
 * recorded Node+entry → a `slopsquatshield` found on PATH (not this launcher) → fail open,
 * loudly. Failing open means exit 1 for `hook` (hosts treat that as a non-blocking error
 * and show stderr), and passing straight through to the real tool for `npm|pip|mvn` — a
 * stale launcher must never brick a package manager (NFR-3.1).
 */
export function buildPosixLauncher(location: Pick<SelfLocation, 'nodePath' | 'entryPath'>): string {
  return `#!/bin/sh
# Generated by \`slopsquatshield init\` — do not edit; re-run \`slopsquatshield init\` to refresh.
NODE=${shQuote(location.nodePath)}
ENTRY=${shQuote(location.entryPath)}

if [ -x "$NODE" ] && [ -f "$ENTRY" ]; then
  exec "$NODE" "$ENTRY" "$@"
fi

# Recorded paths are gone (Node upgraded/removed?). Try a PATH install, skipping this launcher.
SELF_DIR=$(cd "$(dirname "$0")" && pwd)
OLD_IFS=$IFS
IFS=:
for dir in $PATH; do
  [ "$dir" = "$SELF_DIR" ] && continue
  if [ -x "$dir/slopsquatshield" ]; then
    IFS=$OLD_IFS
    exec "$dir/slopsquatshield" "$@"
  fi
done
IFS=$OLD_IFS

echo "${STALE_MESSAGE}" >&2

case "$1" in
  npm|pip|mvn)
    # Fail open: run the real tool, with the launcher and shim dirs off PATH (no recursion).
    tool=$1
    shift
    # The CI shims (shell/ci-shim.ts) live beside bin/. A shell function calling us doesn't set
    # the shim-dir variable, so without this the real-tool lookup found the shim, which called
    # this launcher again and printed the message twice (#3).
    DEFAULT_SHIM_DIR=$(dirname "$SELF_DIR")/shims
    CLEAN_PATH=
    IFS=:
    for dir in $PATH; do
      [ "$dir" = "$SELF_DIR" ] && continue
      [ "$dir" = "$DEFAULT_SHIM_DIR" ] && continue
      [ -n "\${${SHIM_DIR_ENV}:-}" ] && [ "$dir" = "\${${SHIM_DIR_ENV}}" ] && continue
      CLEAN_PATH="\${CLEAN_PATH:+$CLEAN_PATH:}$dir"
    done
    IFS=$OLD_IFS
    PATH=$CLEAN_PATH exec "$tool" "$@"
    ;;
esac
exit 1
`;
}

/** Windows `.cmd` launcher (cmd.exe, Cursor). No PATH fallback: a stale one fails open for hooks only. */
export function buildCmdLauncher(location: Pick<SelfLocation, 'nodePath' | 'entryPath'>): string {
  return [
    '@echo off',
    'rem Generated by `slopsquatshield init` - do not edit; re-run `slopsquatshield init` to refresh.',
    `set "NODE=${location.nodePath}"`,
    `set "ENTRY=${location.entryPath}"`,
    'if exist "%NODE%" if exist "%ENTRY%" (',
    '  "%NODE%" "%ENTRY%" %*',
    '  exit /b %ERRORLEVEL%',
    ')',
    `echo ${STALE_MESSAGE} 1>&2`,
    'exit /b 1',
    '',
  ].join('\r\n');
}

/** PowerShell launcher — avoids batch `%*` quoting; fails open to the real tool for npm|pip|mvn. */
export function buildPowerShellLauncher(
  location: Pick<SelfLocation, 'nodePath' | 'entryPath'>,
): string {
  const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
  return [
    '# Generated by `slopsquatshield init` - do not edit; re-run `slopsquatshield init` to refresh.',
    `$Node = ${q(location.nodePath)}`,
    `$Entry = ${q(location.entryPath)}`,
    'if ((Test-Path $Node) -and (Test-Path $Entry)) {',
    '  & $Node $Entry @args',
    '  exit $LASTEXITCODE',
    '}',
    `[Console]::Error.WriteLine("${STALE_MESSAGE}")`,
    "if ($args.Count -gt 0 -and @('npm','pip','mvn') -contains $args[0]) {",
    '  $selfDir = $PSScriptRoot',
    "  $shimDir = Join-Path (Split-Path $PSScriptRoot -Parent) 'shims'",
    '  $env:PATH = (($env:PATH -split [IO.Path]::PathSeparator) | Where-Object { $_ -ne $selfDir -and $_ -ne $shimDir -and $_ -ne $env:SLOPSQUATSHIELD_SHIM_DIR }) -join [IO.Path]::PathSeparator',
    '  $tool = $args[0]',
    '  $rest = @($args | Select-Object -Skip 1)',
    '  & $tool @rest',
    '  exit $LASTEXITCODE',
    '}',
    'exit 1',
    '',
  ].join('\r\n');
}

/** Windows drive path -> WSL mount path (default `/mnt` automount), e.g. C:\\a\\b.exe -> /mnt/c/a/b.exe. */
export function windowsToWslPosix(windowsPath: string): string {
  const match = /^([A-Za-z]):[\\/](.*)$/.exec(windowsPath);
  if (!match) return windowsPath.replace(/\\/g, '/');
  return `/mnt/${match[1].toLowerCase()}/${match[2].replace(/\\/g, '/')}`;
}

export interface WriteLauncherOptions {
  home?: string;
  platform?: string;
  location: SelfLocation;
}

function writeIfChanged(path: string, content: string, mode?: number): void {
  const existing = existsSync(path) ? readFileSync(path, 'utf-8') : undefined;
  if (existing !== content) {
    mkdirSync(join(path, '..'), { recursive: true });
    writeFileSync(path, content);
  }
  if (mode !== undefined) chmodSync(path, mode);
}

/** Writes the launcher files for this platform (idempotent) and returns the primary path. */
export function writeLauncher(options: WriteLauncherOptions): string {
  const home = options.home ?? homedir();
  const platform = options.platform ?? process.platform;
  const dir = launcherDir(home);
  mkdirSync(dir, { recursive: true });

  // POSIX script everywhere — on Windows it serves Git Bash (Claude Code's hook shell there).
  writeIfChanged(join(dir, LAUNCHER_NAME), buildPosixLauncher(options.location), 0o755);
  if (platform === 'win32') {
    writeIfChanged(join(dir, `${LAUNCHER_NAME}.cmd`), buildCmdLauncher(options.location));
    writeIfChanged(join(dir, `${LAUNCHER_NAME}.ps1`), buildPowerShellLauncher(options.location));
  }
  return launcherPath(home, platform);
}

export interface WslLauncherOptions {
  distro: string;
  /** The distro home as a Windows-writable UNC path (`WslHome.windowsPath`). */
  windowsHome: string;
  /** The distro home as a POSIX path (`WslHome.posixPath`) — used for the exec bit. */
  posixHome: string;
  location: SelfLocation;
  /** Injectable so tests never spawn a real wsl.exe. */
  chmodExecutable?: (distro: string, posixPath: string) => void;
}

function defaultChmodExecutable(distro: string, posixPath: string): void {
  execFileSync('wsl.exe', ['-d', distro, '-e', 'chmod', '+x', posixPath]);
}

/**
 * WSL launcher for the Windows-`node.exe`-under-WSL case: lives in the
 * distro's own home, runs `node.exe` through its `/mnt/<drive>` path with the CLI entry kept
 * as a Windows path (what `node.exe` needs). Plain LF line endings — `sh` rejects CRLF.
 */
export function writeWslLauncher(options: WslLauncherOptions): string {
  const content = buildPosixLauncher({
    nodePath: windowsToWslPosix(options.location.nodePath),
    entryPath: options.location.entryPath,
  });
  const winPath = join(launcherDir(options.windowsHome), LAUNCHER_NAME);
  writeIfChanged(winPath, content);
  (options.chmodExecutable ?? defaultChmodExecutable)(
    options.distro,
    `${options.posixHome}/.config/slopsquatshield/bin/${LAUNCHER_NAME}`,
  );
  return `${options.posixHome}/.config/slopsquatshield/bin/${LAUNCHER_NAME}`;
}

export type LauncherState = 'ok' | 'missing' | 'stale';

/** Reads back a launcher's recorded Node/entry paths and checks they still exist. */
export function inspectLauncher(
  home: string = homedir(),
  exists: (p: string) => boolean = existsSync,
): { state: LauncherState; nodePath?: string; entryPath?: string } {
  const path = join(launcherDir(home), LAUNCHER_NAME);
  if (!existsSync(path)) return { state: 'missing' };
  const text = readFileSync(path, 'utf-8');
  const nodePath = /^NODE='(.*)'$/m.exec(text)?.[1]?.replace(/'\\''/g, "'");
  const entryPath = /^ENTRY='(.*)'$/m.exec(text)?.[1]?.replace(/'\\''/g, "'");
  if (!nodePath || !entryPath) return { state: 'stale' };
  return exists(nodePath) && exists(entryPath)
    ? { state: 'ok', nodePath, entryPath }
    : { state: 'stale', nodePath, entryPath };
}

/**
 * Self-heal: if the launcher's recorded paths vanished (Node upgraded, package reinstalled)
 * and the *running* CLI is a persistent install, rewrite it. Cheap (two `stat`s), so safe to
 * call at the top of every non-hook command; never throws — repair is best-effort.
 */
export function refreshLauncherIfStale(options: {
  location: SelfLocation;
  home?: string;
  platform?: string;
}): boolean {
  try {
    if (options.location.ephemeral) return false;
    const home = options.home ?? homedir();
    if (inspectLauncher(home).state !== 'stale') return false;
    writeLauncher({ home, platform: options.platform, location: options.location });
    return true;
  } catch {
    return false;
  }
}
